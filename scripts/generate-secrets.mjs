#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = resolve(__dirname, '..');

/**
 * Parses a .env file into a key-value map without external dependencies.
 * Supports comments, optional `export ` prefix, single/double quotes, and `\n` escapes.
 */
export function parseEnvFile(content) {
  const result = {};
  for (const rawLine of content.split(/\r?\n/)) {
    const trimmed = rawLine.trim();
    if (!trimmed || trimmed.startsWith('#')) {
      continue;
    }
    const line = trimmed.startsWith('export ') ? trimmed.slice(7).trim() : trimmed;
    const eqIndex = line.indexOf('=');
    if (eqIndex <= 0) {
      continue;
    }
    const key = line.slice(0, eqIndex).trim();
    let value = line.slice(eqIndex + 1).trim();

    if (
      (value.startsWith('"') && value.endsWith('"') && value.length >= 2) ||
      (value.startsWith("'") && value.endsWith("'") && value.length >= 2)
    ) {
      const quote = value[0];
      value = value.slice(1, -1);
      if (quote === '"') {
        value = value
          .replace(/\\n/g, '\n')
          .replace(/\\r/g, '\r')
          .replace(/\\t/g, '\t')
          .replace(/\\"/g, '"')
          .replace(/\\\\/g, '\\');
      }
    } else {
      const commentIndex = value.indexOf(' #');
      if (commentIndex >= 0) {
        value = value.slice(0, commentIndex).trim();
      }
    }

    result[key] = value;
  }
  return result;
}

/**
 * Builds the normalized secrets object from merged environment values.
 */
export function buildSecretsObject(env) {
  const allowedChatIds = String(env.ALLOWED_CHAT_IDS ?? '')
    .split(',')
    .map((part) => part.trim())
    .filter(Boolean)
    .map((part) => Number(part))
    .filter((id) => Number.isSafeInteger(id));

  const adminIdSet = new Set();
  for (const rawList of [env.OWNER_ID, env.ADMIN_USER_IDS]) {
    for (const part of String(rawList ?? '').split(',')) {
      const trimmed = part.trim();
      if (!trimmed) {
        continue;
      }
      const id = Number(trimmed);
      if (Number.isSafeInteger(id) && id > 0) {
        adminIdSet.add(id);
      }
    }
  }
  const adminUserIds = [...adminIdSet];

  const rawBotId = String(env.BOT_ID ?? '').trim();
  const parsedBotId = rawBotId ? Number(rawBotId) : null;

  const rawMaxDepth = String(env.BRANCH_MAX_DEPTH ?? '').trim();
  const parsedMaxDepth = rawMaxDepth ? Number(rawMaxDepth) : null;

  const rawMaxContextChars = String(env.BRANCH_MAX_CONTEXT_CHARS ?? '').trim();
  const parsedMaxContextChars = rawMaxContextChars ? Number(rawMaxContextChars) : null;

  const rawSecretaryAllowAll = String(env.SECRETARY_ALLOW_ALL ?? '').trim().toLowerCase();
  const secretaryAllowAll = rawSecretaryAllowAll === 'true' || rawSecretaryAllowAll === '1';

  const rawSecretaryMarkAsRead = String(env.SECRETARY_MARK_AS_READ ?? '').trim().toLowerCase();
  const secretaryMarkAsRead =
    rawSecretaryMarkAsRead === 'false' || rawSecretaryMarkAsRead === '0' ? false : true;

  return {
    openRouterApiKey: String(env.OPENROUTER_API ?? '').trim(),
    geminiApiKey: String(env.GEMINI_API ?? '').trim(),
    openRouterModel: String(env.OPENROUTER_MODEL ?? '').trim(),
    geminiModel: String(env.GEMINI_MODEL ?? '').trim(),
    allowedChatIds,
    adminUserIds,
    systemPrompt: String(env.SYSTEM_PROMPT ?? '').trim(),
    secretarySystemPrompt: String(env.SECRETARY_PROMPT ?? '').trim(),
    secretaryAllowAll,
    secretaryMarkAsRead,
    botId: Number.isSafeInteger(parsedBotId) ? parsedBotId : null,
    botUsername: String(env.BOT_USERNAME ?? '').trim().replace(/^@/, ''),
    branchMaxDepth:
      Number.isInteger(parsedMaxDepth) && parsedMaxDepth > 0 ? parsedMaxDepth : null,
    branchMaxContextChars:
      Number.isInteger(parsedMaxContextChars) && parsedMaxContextChars > 0
        ? parsedMaxContextChars
        : null,
  };
}

/**
 * Renders the JS module content for tgcloud/lib/secrets.js.
 */
export function renderSecretsModule(secrets) {
  return [
    '// Auto-generated by scripts/generate-secrets.mjs — DO NOT COMMIT TO GIT.',
    '// Deployed to Telegram Serverless via `npx tgcloud push`.',
    `export const SECRETS = Object.freeze(${JSON.stringify(secrets, null, 2)});`,
    '',
  ].join('\n');
}

export function generateSecrets({
  envFile = resolve(PROJECT_ROOT, '.env'),
  outputFile = resolve(PROJECT_ROOT, 'tgcloud/lib/secrets.js'),
  processEnv = process.env,
  checkOnly = false,
  strict = false,
} = {}) {
  const fileEnv = existsSync(envFile) ? parseEnvFile(readFileSync(envFile, 'utf8')) : {};
  // process.env overrides .env file values
  const merged = { ...fileEnv, ...processEnv };
  const secrets = buildSecretsObject(merged);

  const missingBothLlmKeys = !secrets.openRouterApiKey && !secrets.geminiApiKey;
  if (missingBothLlmKeys) {
    const msg =
      'Warning: Neither OPENROUTER_API nor GEMINI_API is configured. ' +
      'The bot will respond to /start, but AI answers will fail until at least one key is set in .env.';
    if (strict) {
      throw new Error(msg);
    }
    console.warn(msg);
  }

  const content = renderSecretsModule(secrets);
  if (!checkOnly) {
    mkdirSync(dirname(outputFile), { recursive: true });
    writeFileSync(outputFile, content, 'utf8');
  }

  return { secrets, content, outputFile };
}

function parseCliArgs(argv) {
  const opts = { checkOnly: false, strict: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--check-only') {
      opts.checkOnly = true;
    } else if (arg === '--strict') {
      opts.strict = true;
    } else if (arg === '--env-file' && argv[i + 1]) {
      opts.envFile = resolve(argv[++i]);
    } else if (arg === '--output' && argv[i + 1]) {
      opts.outputFile = resolve(argv[++i]);
    }
  }
  return opts;
}

const isDirectExecution =
  process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isDirectExecution) {
  const opts = parseCliArgs(process.argv.slice(2));
  const { outputFile } = generateSecrets(opts);
  if (opts.checkOnly) {
    console.log('Secrets configuration check passed.');
  } else {
    console.log(`Generated ${outputFile}`);
  }
}
